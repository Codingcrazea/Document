// backend/api/payment/checkout.ts
// Responsive Hosted Razorpay Standard Checkout Page (UPI, Cards, Netbanking, Wallets)

declare const process: {
  env: Record<string, string | undefined>;
};

interface VercelRequest {
  method?: string;
  query?: Record<string, string | string[]>;
}

interface VercelResponse {
  setHeader(name: string, value: string): void;
  status(code: number): VercelResponse;
  send(body: string): void;
}

export default async function handler(req: VercelRequest, res: VercelResponse) {
  const rawOrderId = (req.query?.order_id as string) || '';
  const amount = (req.query?.amount as string) || '49900';
  const keyId = (req.query?.key_id as string) || process.env.RAZORPAY_KEY_ID || 'rzp_live_rrRegsiFRtrkLi';
  const displayAmount = (Number(amount) / 100).toFixed(0);

  // Only pass order_id if it's an authentic Razorpay order generated by the API
  const isAuthenticRzpOrder =
    rawOrderId &&
    rawOrderId.startsWith('order_') &&
    rawOrderId.length >= 18 &&
    !rawOrderId.includes('test_101') &&
    !rawOrderId.includes('sim_');

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>DocUtility Pro - VIP Checkout</title>
  <script src="https://checkout.razorpay.com/v1/checkout.js"></script>
  <style>
    * { box-sizing: border-box; }
    body {
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
      background: #0B0F19;
      color: #F8FAFC;
      display: flex;
      flex-direction: column;
      align-items: center;
      justify-content: center;
      min-height: 100vh;
      margin: 0;
      padding: 20px;
    }
    .checkout-card {
      background: #141824;
      border-radius: 20px;
      padding: 36px 28px;
      max-width: 420px;
      width: 100%;
      border: 1px solid rgba(255, 255, 255, 0.1);
      box-shadow: 0 16px 40px rgba(0, 0, 0, 0.6);
      text-align: center;
    }
    .badge {
      display: inline-block;
      background: rgba(229, 9, 20, 0.15);
      color: #E50914;
      font-weight: 700;
      font-size: 12px;
      letter-spacing: 1px;
      text-transform: uppercase;
      padding: 6px 14px;
      border-radius: 20px;
      margin-bottom: 16px;
      border: 1px solid rgba(229, 9, 20, 0.3);
    }
    h1 {
      font-size: 24px;
      font-weight: 800;
      margin: 0 0 10px 0;
      color: #FFFFFF;
    }
    p {
      color: #94A3B8;
      font-size: 14px;
      line-height: 1.5;
      margin: 0 0 24px 0;
    }
    .price-box {
      background: #1E2333;
      border-radius: 12px;
      padding: 20px;
      margin-bottom: 24px;
    }
    .price-label {
      font-size: 12px;
      color: #94A3B8;
      text-transform: uppercase;
    }
    .price-value {
      font-size: 38px;
      font-weight: 900;
      color: #38BDF8;
      margin-top: 4px;
    }
    .pay-btn {
      background: #E50914;
      color: #FFFFFF;
      border: none;
      border-radius: 50px;
      padding: 16px 32px;
      font-size: 16px;
      font-weight: 700;
      cursor: pointer;
      width: 100%;
      box-shadow: 0 6px 20px rgba(229, 9, 20, 0.4);
      transition: all 0.2s ease;
      margin-bottom: 12px;
    }
    .pay-btn:hover {
      background: #b80710;
    }
    .sim-btn {
      background: rgba(255, 255, 255, 0.08);
      color: #94A3B8;
      border: 1px solid rgba(255, 255, 255, 0.15);
      border-radius: 50px;
      padding: 12px 24px;
      font-size: 13px;
      font-weight: 600;
      cursor: pointer;
      width: 100%;
      transition: all 0.2s;
    }
    .sim-btn:hover {
      background: rgba(255, 255, 255, 0.15);
      color: #FFFFFF;
    }
    .status-box {
      display: none;
      border-radius: 10px;
      padding: 12px 16px;
      margin-top: 18px;
      font-size: 13px;
      text-align: left;
    }
    .status-box.error {
      display: block;
      background: rgba(239, 68, 68, 0.15);
      border: 1px solid rgba(239, 68, 68, 0.3);
      color: #FCA5A5;
    }
  </style>
</head>
<body>
  <div class="checkout-card">
    <div class="badge">DocUtility Pro VIP</div>
    <h1>Unlock Lifetime Access</h1>
    <p>Unlimited offline OCR, PDF merger, compressor, metadata editor, and ad-free experience.</p>
    
    <div class="price-box">
      <div class="price-label">One-Time Lifetime Fee</div>
      <div class="price-value">₹${displayAmount}</div>
    </div>

    <button id="rzp-btn" class="pay-btn" onclick="openRazorpay()">Pay ₹${displayAmount} via Razorpay</button>
    <button class="sim-btn" onclick="simulatePayment()">⚡ Simulate Payment Success (VIP Test Mode)</button>

    <div id="status-box" class="status-box"></div>
  </div>

  <script>
    function openRazorpay() {
      try {
        var options = {
          "key": "${keyId}",
          "amount": "${amount}",
          "currency": "INR",
          "name": "DocUtility Pro",
          "description": "VIP Lifetime License",
          ${isAuthenticRzpOrder ? `"order_id": "${rawOrderId}",` : ''}
          "theme": { "color": "#E50914" },
          "prefill": {
            "name": "DocUtility Pro User"
          },
          "handler": function (response) {
            window.location.href = "https://documentreader-two.vercel.app/api/payment/callback?payment_id=" +
              encodeURIComponent(response.razorpay_payment_id) +
              "&order_id=" + encodeURIComponent(response.razorpay_order_id || "${rawOrderId || 'order_direct'}");
          }
        };
        var rzp = new Razorpay(options);
        rzp.on('payment.failed', function (response) {
          var box = document.getElementById('status-box');
          box.className = 'status-box error';
          box.innerHTML = "<b>❌ Razorpay Error:</b> " + (response.error.description || response.error.code);
        });
        rzp.open();
      } catch (err) {
        var box = document.getElementById('status-box');
        box.className = 'status-box error';
        box.innerHTML = "<b>⚠️ Razorpay Launch Error:</b> " + err.message;
      }
    }

    function simulatePayment() {
      var fakePayId = "pay_sim_" + Date.now();
      window.location.href = "https://documentreader-two.vercel.app/api/payment/callback?payment_id=" + fakePayId + "&order_id=${rawOrderId || 'order_sim'}";
    }

    window.onload = function() {
      setTimeout(openRazorpay, 500);
    };
  </script>
</body>
</html>`;

  res.setHeader('Content-Type', 'text/html; charset=utf-8');
  res.status(200).send(html);
}
